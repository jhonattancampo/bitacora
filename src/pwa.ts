/* =========================================================
   pwa.ts — Service worker wiring.
   The worker itself is generated by vite-plugin-pwa (Workbox)
   at build time instead of being hand-written, so the version
   number no longer has to be bumped by hand. Registration and
   the "Buscar actualización de la app" button behave the same
   as before: a new build takes over on the next reload, and the
   button forces that check right now.
   ========================================================= */

let registration: ServiceWorkerRegistration | null = null;

export function registerServiceWorker(): void {
  if (!("serviceWorker" in navigator)) return;
  // No worker is generated in dev; registering it would only log a MIME error.
  // Offline behaviour is verified against a real build (`npm run preview`).
  if (import.meta.env.DEV) return;
  window.addEventListener("load", () => {
    navigator.serviceWorker
      .register("/sw.js", { scope: "/" })
      .then((r) => {
        registration = r;
      })
      .catch(() => {});
  });
}

/**
 * Ask the browser to look for a newer worker, then reload.
 * Caches are deliberately NOT cleared here: Workbox keeps the app shell in a
 * precache it manages itself, and wiping it would leave the app unable to open
 * offline until the next successful install.
 */
export async function checkForUpdate(): Promise<void> {
  if (!("serviceWorker" in navigator)) {
    location.reload();
    return;
  }
  try {
    const regs = registration ? [registration] : await navigator.serviceWorker.getRegistrations();
    await Promise.all(regs.map((r) => r.update()));
  } catch {
    /* offline, or the worker is not installed yet: reloading is still correct */
  }
  location.reload();
}
